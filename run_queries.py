"""Runs queries.sql against sales.db and writes the results to results.md."""
import sqlite3, re
con = sqlite3.connect("sales.db")
blocks = re.split(r"^-- ==== ", open("queries.sql").read(), flags=re.M)[1:]
out = ["# Query results\n", "Generated by `run_queries.py` from `queries.sql` on the synthetic dataset.\n"]
for b in blocks:
    title, _, sql = b.partition("\n")
    if title.startswith("SETUP"):
        con.executescript(sql); continue
    cur = con.execute(sql)
    cols = [d[0] for d in cur.description]
    rows = cur.fetchall()
    out.append(f"\n## {title}\n")
    out.append("| " + " | ".join(cols) + " |")
    out.append("|" + "|".join(["---"] * len(cols)) + "|")
    def fmt(c, v):
        if v is None: return ""
        if c == "yr": return str(v)
        if isinstance(v, float): return f"{v:,.0f}" if v.is_integer() else f"{v:,.1f}"
        if isinstance(v, int): return f"{v:,}"
        return str(v)
    for r in rows:
        out.append("| " + " | ".join(fmt(c, v) for c, v in zip(cols, r)) + " |")
open("results.md","w").write("\n".join(out) + "\n")
print("\n".join(out))
